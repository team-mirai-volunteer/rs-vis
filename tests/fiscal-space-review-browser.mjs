import { chromium, expect } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdirSync } from 'node:fs';
const origin = process.env.FISCAL_SPACE_BASE_URL ?? 'http://localhost:3108';
const browser = await chromium.launch({ headless: true });
const errors = [];
mkdirSync('test-results/fiscal-space', { recursive: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  page.on('pageerror', e => errors.push(e.message));
  page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
  await page.goto(`${origin}/fiscal-space`, { timeout: 120000 });
  // Wait for React handlers before Playwright changes SSR form attributes.
  await page.waitForFunction(() => {
    const fields = [...document.querySelectorAll('main input')];
    return fields.length > 0 && fields.every(el => Object.keys(el).some(k => k.startsWith('__reactProps$')));
  });
  await expect(page.getByRole('heading', { name: '政策を積み上げる' })).toBeVisible();
  const y = await page.getByRole('region', { name: '政策の操作パネル' }).evaluate(el => el.getBoundingClientRect().top + scrollY);
  assert(y < 600, `Policy controls begin at ${y}px`);
  await expect(page.getByTestId('input-overview')).toContainText('0.00兆円');
  await page.getByRole('button', { name: '例：社会保険料減税中心の15兆円配分' }).click();
  await expect(page.getByTestId('input-overview')).toContainText('15.00兆円');
  await expect(page.getByTestId('input-overview')).toContainText('この配分の参考上限');
  await expect(page.getByRole('meter', { name: '産業別能力の閾値利用率' })).toHaveCount(0);
  await expect(page.getByRole('meter', { name: '電力供給能力の閾値利用率' })).toHaveCount(0);
  await page.screenshot({ path: 'test-results/fiscal-space/review-desktop.png' });
  for (const name of ['社会保険料減税', '研究開発', '送電網投資', '防衛', '子育て']) await page.getByLabel(`${name}・数値で入力`, { exact: true }).fill('0');
  await page.getByLabel('公共投資・数値で入力', { exact: true }).fill('10');
  const conditions = page.getByText('経済状態・評価条件を変える', { exact: true });
  await conditions.click();
  await page.getByLabel('制約の評価期間').selectOption('1');
  await page.getByLabel('潜在GDPギャップ（年0）・数値で入力', { exact: true }).fill('-5');
  const result = page.getByRole('heading', { name: '年1の結果' }).locator('..').locator('..');
  const slack = await result.innerText();
  await page.getByLabel('潜在GDPギャップ（年0）・数値で入力', { exact: true }).fill('3');
  await expect.poll(() => result.innerText()).not.toEqual(slack);
  await expect(result).toContainText('消費税直接効果を除くCPI');
  await expect(result).toContainText('借換・新発金利');
  await page.getByRole('button', { name: '初期条件に戻す' }).click();
  await page.getByRole('button', { name: '例：社会保険料減税中心の15兆円配分' }).click();
  const models = page.getByRole('region', { name: '参考上限の感度' });
  await expect(models.locator('tbody tr')).toHaveCount(3);
  await page.getByLabel('使用する生産モデル').selectOption('ces');
  await expect(page.getByLabel('使用する生産モデル')).toHaveValue('ces');
  const long = page.getByRole('region', { name: '長期シナリオ' });
  const lowRate = await long.locator('tbody').innerText();
  await page.getByLabel('長期の借換金利・数値で入力', { exact: true }).fill('6');
  await expect.poll(() => long.locator('tbody').innerText()).not.toEqual(lowRate);
  const taxDetails = page.getByText(/^ほかの.*政策を追加する$/);
  await taxDetails.click();
  await page.getByLabel('消費税減税・数値で入力', { exact: true }).fill('35');
  await expect(page.getByTestId('annual-total')).toHaveText('50.0兆円');
  await page.getByText('GDPギャップ・金利・消費税の接続条件', { exact: true }).click();
  await page.getByLabel('消費税1ポイントの減収額・数値で入力', { exact: true }).fill('1');
  await expect(page.getByTestId('annual-total')).toHaveText('25.0兆円');
  await page.getByRole('button', { name: '初期条件に戻す' }).click();
  await page.getByRole('button', { name: '例：社会保険料減税中心の15兆円配分' }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.evaluate(() => scrollTo(0, 0));
  const mobileY = await page.getByRole('region', { name: '政策の操作パネル' }).evaluate(el => el.getBoundingClientRect().top + scrollY);
  assert(mobileY < 600);
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
  await page.screenshot({ path: 'test-results/fiscal-space/review-mobile.png' });
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ policyPanelY: y, mobilePanelY: mobileY, errors, result: 'passed' }));
} finally { await browser.close(); }
