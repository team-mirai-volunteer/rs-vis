import { chromium, expect } from '@playwright/test';
import { mkdir } from 'node:fs/promises';

const browser = await chromium.launch();
const errors = [];
await mkdir('test-results/tax-expenditures', { recursive: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  page.on('pageerror', e => errors.push(e.message));
  await page.goto(`${process.env.BASE_URL || 'http://127.0.0.1:3000'}/tax-expenditures`);
  await expect(page.getByRole('heading', { name: '租税特別措置(試作)', exact: true })).toBeVisible();
  await expect(page.getByRole('status')).toContainText('79 / 79');
  const assessments = page.getByRole('region', { name: '租特の妥当性評価', exact: true });
  await expect(assessments).toBeVisible();
  await assessments.getByLabel('評価表の並び順').selectOption('verification');
  await expect(assessments.locator('tbody tr').first()).toContainText('沖縄・特定地域（繰越税額控除）');
  await assessments.getByRole('button', { name: '賃上げ促進税制の評価根拠を開く' }).click();
  const rationale = assessments.getByRole('region', { name: '賃上げ促進税制の評価根拠' });
  await expect(rationale.getByRole('heading', { name: '検証可能性：2 / 4点' })).toBeVisible();
  await expect(rationale.getByText(/資料不足：0点/)).toHaveCount(2);
  const identification = rationale.getByRole('region', { name: '賃上げ税制の交絡を切る分析計画' });
  await expect(identification).toContainText('設計案・推定未実施');
  await identification.getByText('推定に進むための3条件とデータの状況').click();
  await expect(identification.getByText(/同じ境界で効く施策を分離できなければ/)).toBeVisible();
  await identification.getByText('取得した企業データ：13社・39観測').click();
  const companies = identification.getByRole('region', { name: '公開有報の企業比較' });
  await expect(companies.getByRole('status')).toContainText('表示：9社');
  await expect(companies.getByText('人数の定義変更あり', { exact: true })).toBeVisible();
  await companies.getByLabel('企業比較の人数範囲').selectOption('250');
  await expect(companies.getByRole('status')).toHaveText('表示：5社。2,000人以下：3社 ／ 2,000人超：2社');
  await companies.getByLabel('企業比較の人数範囲').selectOption('100');
  await expect(companies.getByText('この範囲の企業は今回の標本にありません。')).toBeVisible();
  await companies.getByLabel('企業比較の人数範囲').selectOption('all');
  await expect(companies.locator('tbody tr')).toHaveCount(13);
  const csv = await page.request.get(new URL('/tax-expenditures/company-panel.csv', page.url()).href);
  expect(csv.ok()).toBe(true);
  expect((await csv.text()).trim().split('\n')).toHaveLength(40);
  await companies.screenshot({ path: 'test-results/tax-expenditures/company-panel-desktop.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await companies.screenshot({ path: 'test-results/tax-expenditures/company-panel-mobile.png' });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await assessments.scrollIntoViewIfNeeded();
  await page.screenshot({ path: 'test-results/tax-expenditures/assessments.png' });
  await rationale.getByRole('button', { name: '閉じる' }).click();
  await expect(identification).toHaveCount(0);
  await assessments.getByRole('button', { name: '企業版ふるさと納税（法人税分）の評価根拠を開く' }).click();
  await expect(assessments.getByRole('region', { name: '企業版ふるさと納税（法人税分）の評価根拠' })).toContainText('内閣府・企業版ふるさと納税');
  await expect(assessments).toContainText('30 / 35項目');
  await assessments.getByRole('button', { name: '閉じる' }).click();
  const chart = page.getByRole('region', { name: '税額控除の適用実績' });
  await expect(chart).toBeVisible();
  await expect(chart.getByRole('button', { name: /制度詳細を開く/ })).toHaveCount(7);
  await chart.getByRole('button', { name: '研究開発税制の制度詳細を開く' }).click();
  await expect(page.locator('#mof-2024-r24')).toHaveAttribute('open', '');
  await chart.getByText('研究開発税制の内訳', { exact: true }).click();
  await expect(chart.getByText('(1) 一般の試験研究費')).toBeVisible();
  await chart.scrollIntoViewIfNeeded();
  await page.screenshot({ path: 'test-results/tax-expenditures/chart.png' });
  await page.screenshot({ path: 'test-results/tax-expenditures/desktop.png' });
  await page.getByRole('searchbox').fill('ふるさと納税');
  await expect(page.getByRole('status')).toContainText('1 / 79');
  await expect(chart.getByRole('button', { name: /制度詳細を開く/ })).toHaveCount(1);
  await expect(chart.getByRole('button', { name: /企業版ふるさと納税/ })).toContainText('28.99 億円');
  const measure = page.locator('details').filter({ hasText: '認定地方公共団体の寄附活用事業' });
  await measure.locator('summary').click();
  await expect(measure.getByRole('cell', { name: '2,899,075', exact: true })).toBeVisible();
  await page.getByLabel('適用年度', { exact: true }).selectOption('2022');
  await expect(assessments).toContainText('金額は選択中の2022年度');
  await expect(chart.getByRole('button', { name: /企業版ふるさと納税/ })).toContainText('13.31 億円');
  await expect(measure.getByRole('cell', { name: '1,272,063', exact: true })).toBeVisible();
  await page.getByRole('searchbox').fill('存在しない制度xyz');
  await expect(page.getByText('該当する制度がありません。', { exact: false })).toBeVisible();
  await expect(chart.getByText('この検索条件ではグラフ対象の制度がありません。')).toBeVisible();
  await page.getByRole('button', { name: 'RSとの関連を確認する' }).click();
  await expect(page.getByRole('status')).toContainText('1 / 79');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('details').filter({ hasText: '認定地方公共団体の寄附活用事業' }).locator('summary').click();
  await page.screenshot({ path: 'test-results/tax-expenditures/mobile.png', fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByRole('link', { name: /地方創生応援税制（企業版ふるさと納税）普及促進事業/ }).click();
  await expect(page).toHaveURL(/quality\?fiscalYear=2024&pid=127&detail=127/);
  await expect(page.getByText('地方創生応援税制(企業版ふるさと納税)普及促進事業', { exact: true }).first()).toBeVisible({ timeout: 60000 });
  expect(errors).toEqual([]);
  console.log('Tax expenditures: search, years, missing result, RS link, mobile overflow passed.');
} finally {
  await browser.close();
}
