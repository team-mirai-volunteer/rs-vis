/**
 * 値の集合を、コード表の並び順（`order`）で並べ替える。特別会計の共管表記のように
 * 複数の名称が1つの文字列に含まれる場合は、含まれる名称のうち最も番号の若いもので
 * ランク付けする。コード表に無い値は末尾へ、五十音順で並べる。
 */
export function sortByCodeOrder(values: string[], order: readonly string[]): string[] {
  const rankOf = (value: string): number => {
    let best = Infinity;
    for (let i = 0; i < order.length; i++) {
      if (value.includes(order[i]) && i < best) best = i;
    }
    return best;
  };
  return [...values].sort((a, b) => {
    const ra = rankOf(a);
    const rb = rankOf(b);
    if (ra !== rb) return ra - rb;
    return a.localeCompare(b, 'ja');
  });
}
